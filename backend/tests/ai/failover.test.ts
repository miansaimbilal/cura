import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { AIFailoverEngine } from '../../src/modules/ai/failover';
import { AIProviderRegistry } from '../../src/modules/ai/registry';
import { AllProvidersFailedError, AIProviderError } from '../../src/modules/ai/errors';
import type { AIModuleConfig } from '../../src/modules/ai/config';
import type { AITextRequest } from '../../src/modules/ai/types';

describe('AI Failover Engine (Background AI Operations)', () => {
  const originalFetch = globalThis.fetch;

  const mockConfig: AIModuleConfig = {
    defaultProvider: 'gemini',
    defaultTimeoutMs: 10000,
    failoverOrder: ['gemini', 'groq', 'openrouter', 'cloudflare', 'xai'],
    providers: {
      gemini: { apiKey: 'key-gemini', defaultModel: 'gemini-3.8-flash' },
      groq: { apiKey: 'key-groq', defaultModel: 'llama-3.3-70b-versatile' },
      openrouter: { apiKey: 'key-openrouter', defaultModel: 'meta-llama/llama-3.3-70b-instruct' },
      cloudflare: { apiKey: 'cf-token', accountId: 'cf-acc', defaultModel: '@cf/meta/llama-3.3-70b-instruct-fp8-fast' },
      xai: { apiKey: 'key-xai', defaultModel: 'grok-3-latest' },
    },
  };

  const sampleRequest: AITextRequest = {
    messages: [{ role: 'user', content: 'Generate background insight' }],
  };

  beforeEach(() => {
    vi.restoreAllMocks();
  });

  afterEach(() => {
    globalThis.fetch = originalFetch;
  });

  it('succeeds on preferred provider without triggering fallback', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    globalThis.fetch = vi.fn().mockResolvedValue({
      status: 200,
      text: async () =>
        JSON.stringify({
          candidates: [{ content: { parts: [{ text: 'Insight generated by Gemini.' }] } }],
        }),
    });

    const result = await engine.executeBackground(sampleRequest);

    expect(result.text).toBe('Insight generated by Gemini.');
    expect(result.provider).toBe('gemini');
    expect(result.fallbackOccurred).toBe(false);
    expect(result.attempts).toHaveLength(1);
    expect(result.attempts[0].provider).toBe('gemini');
  });

  it('fails over to secondary provider when primary returns 429 rate limit', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    let callCount = 0;
    globalThis.fetch = vi.fn().mockImplementation(async (url: string) => {
      callCount++;
      if (url.includes('generativelanguage.googleapis.com')) {
        // Gemini fails with 429
        return {
          status: 429,
          text: async () => JSON.stringify({ error: { message: 'Resource exhausted, rate limited' } }),
        };
      }
      // Groq succeeds
      return {
        status: 200,
        text: async () =>
          JSON.stringify({
            choices: [{ message: { content: 'Fallback insight from Groq.' } }],
          }),
      };
    });

    const result = await engine.executeBackground(sampleRequest);

    expect(result.text).toBe('Fallback insight from Groq.');
    expect(result.provider).toBe('groq');
    expect(result.fallbackOccurred).toBe(true);
    expect(result.attempts).toHaveLength(2);
    expect(result.attempts[0].provider).toBe('gemini');
    expect(result.attempts[0].error?.category).toBe('QUOTA_EXCEEDED');
    expect(result.attempts[1].provider).toBe('groq');
    expect(callCount).toBe(2);
  });

  it('fails over when primary provider times out', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    globalThis.fetch = vi.fn().mockImplementation(async (url: string) => {
      if (url.includes('generativelanguage.googleapis.com')) {
        const err = new Error('The operation was aborted due to timeout');
        err.name = 'AbortError';
        throw err;
      }
      return {
        status: 200,
        text: async () =>
          JSON.stringify({
            choices: [{ message: { content: 'Groq succeeded after timeout.' } }],
          }),
      };
    });

    const result = await engine.executeBackground(sampleRequest);

    expect(result.text).toBe('Groq succeeded after timeout.');
    expect(result.provider).toBe('groq');
    expect(result.fallbackOccurred).toBe(true);
    expect(result.attempts[0].error?.category).toBe('TIMEOUT');
  });

  it('does NOT fallback on non-retryable errors (e.g. INVALID_REQUEST / 400)', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    let callCount = 0;
    globalThis.fetch = vi.fn().mockImplementation(async () => {
      callCount++;
      return {
        status: 400,
        text: async () => JSON.stringify({ error: { message: 'Invalid payload argument' } }),
      };
    });

    await expect(engine.executeBackground(sampleRequest)).rejects.toThrow(AIProviderError);
    // Should stop immediately without trying second provider
    expect(callCount).toBe(1);
  });

  it('does NOT fallback on non-retryable AUTHENTICATION_ERROR (401)', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    let callCount = 0;
    globalThis.fetch = vi.fn().mockImplementation(async () => {
      callCount++;
      return {
        status: 401,
        text: async () => JSON.stringify({ error: { message: 'Unauthorized API key' } }),
      };
    });

    await expect(engine.executeBackground(sampleRequest)).rejects.toThrow(AIProviderError);
    expect(callCount).toBe(1);
  });

  it('skips unconfigured providers during failover sequence', async () => {
    const partialConfig: AIModuleConfig = {
      ...mockConfig,
      providers: {
        ...mockConfig.providers,
        groq: { defaultModel: 'llama-3.3-70b-versatile', apiKey: '' }, // Groq unconfigured
      },
    };

    const registry = new AIProviderRegistry(partialConfig);
    const engine = new AIFailoverEngine(registry);

    globalThis.fetch = vi.fn().mockImplementation(async (url: string) => {
      if (url.includes('generativelanguage.googleapis.com')) {
        return {
          status: 503,
          text: async () => JSON.stringify({ error: 'Service Unavailable' }),
        };
      }
      if (url.includes('openrouter.ai')) {
        return {
          status: 200,
          text: async () =>
            JSON.stringify({
              choices: [{ message: { content: 'OpenRouter answered' } }],
            }),
        };
      }
      throw new Error(`Unexpected call to ${url}`);
    });

    const result = await engine.executeBackground(sampleRequest);

    expect(result.provider).toBe('openrouter');
    // Gemini was attempted, Groq was skipped because unconfigured, OpenRouter succeeded
    expect(result.attempts.map((a) => a.provider)).toEqual(['gemini', 'openrouter']);
  });

  it('never attempts the same provider twice in a failover sequence', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    const attemptedProviders: string[] = [];

    globalThis.fetch = vi.fn().mockImplementation(async (url: string) => {
      if (url.includes('generativelanguage.googleapis.com')) attemptedProviders.push('gemini');
      if (url.includes('groq.com')) attemptedProviders.push('groq');
      if (url.includes('openrouter.ai')) attemptedProviders.push('openrouter');
      if (url.includes('cloudflare.com')) attemptedProviders.push('cloudflare');
      if (url.includes('api.x.ai')) attemptedProviders.push('xai');

      return {
        status: 500,
        text: async () => JSON.stringify({ error: 'Internal error' }),
      };
    });

    await expect(
      engine.executeBackground(sampleRequest, {
        customOrder: ['gemini', 'gemini', 'groq', 'gemini', 'groq'],
      })
    ).rejects.toThrow(AllProvidersFailedError);

    // Each provider should only have been attempted once
    const counts = attemptedProviders.reduce((acc, p) => {
      acc[p] = (acc[p] || 0) + 1;
      return acc;
    }, {} as Record<string, number>);

    expect(counts['gemini']).toBe(1);
    expect(counts['groq']).toBe(1);
  });

  it('respects maxAttempts option', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    let attemptsCount = 0;
    globalThis.fetch = vi.fn().mockImplementation(async () => {
      attemptsCount++;
      return {
        status: 503,
        text: async () => JSON.stringify({ error: 'Unavailable' }),
      };
    });

    await expect(
      engine.executeBackground(sampleRequest, { maxAttempts: 2 })
    ).rejects.toThrow(AllProvidersFailedError);

    expect(attemptsCount).toBe(2);
  });

  it('throws AllProvidersFailedError with complete attempt details when all providers fail', async () => {
    const registry = new AIProviderRegistry(mockConfig);
    const engine = new AIFailoverEngine(registry);

    globalThis.fetch = vi.fn().mockResolvedValue({
      status: 503,
      text: async () => JSON.stringify({ error: 'Unavailable across providers' }),
    });

    try {
      await engine.executeBackground(sampleRequest);
      expect.fail('Should have thrown AllProvidersFailedError');
    } catch (err) {
      expect(err).toBeInstanceOf(AllProvidersFailedError);
      const allErr = err as AllProvidersFailedError;
      expect(allErr.attempts.length).toBe(5);
      expect(allErr.attempts.every((a) => a.category === 'PROVIDER_UNAVAILABLE')).toBe(true);
    }
  });

  describe('Cooldown & Retry-After Management', () => {
    it('sets cooldown on rate-limited provider and prioritizes available providers in subsequent background tasks', async () => {
      const registry = new AIProviderRegistry(mockConfig);
      const engine = new AIFailoverEngine(registry);

      // First run: Gemini 429 with Retry-After: 30, Groq succeeds
      globalThis.fetch = vi.fn().mockImplementation(async (url: string) => {
        if (url.includes('generativelanguage.googleapis.com')) {
          return {
            status: 429,
            headers: new Headers({ 'retry-after': '30' }),
            text: async () => JSON.stringify({ error: { message: 'Too many requests' } }),
          };
        }
        return {
          status: 200,
          headers: new Headers(),
          text: async () => JSON.stringify({ choices: [{ message: { content: 'Groq reply' } }] }),
        };
      });

      const firstRes = await engine.executeBackground(sampleRequest);
      expect(firstRes.provider).toBe('groq');
      expect(firstRes.attempts[0].error?.retryAfterSeconds).toBe(30);

      // Verify Gemini is now in cooldown
      const geminiHealth = registry.getProvider('gemini').getHealth();
      expect(geminiHealth.isAvailable).toBe(false);
      expect(geminiHealth.cooldownUntil).not.toBeNull();

      // Second run: Groq is available, Gemini is cooling down.
      // Failover engine should prioritize Groq first, skipping Gemini!
      const attemptedOrder: string[] = [];
      globalThis.fetch = vi.fn().mockImplementation(async (url: string) => {
        if (url.includes('api.groq.com')) attemptedOrder.push('groq');
        if (url.includes('generativelanguage.googleapis.com')) attemptedOrder.push('gemini');
        return {
          status: 200,
          headers: new Headers(),
          text: async () => JSON.stringify({ choices: [{ message: { content: 'Groq fast reply' } }] }),
        };
      });

      const secondRes = await engine.executeBackground(sampleRequest);
      expect(secondRes.provider).toBe('groq');
      expect(secondRes.fallbackOccurred).toBe(false); // Succeeded on first attempted available provider!
      expect(attemptedOrder).toEqual(['groq']);
    });

    it('recovers provider availability after successful execution', async () => {
      const registry = new AIProviderRegistry(mockConfig);
      const gemini = registry.getProvider('gemini');

      // Simulate a previous failure
      globalThis.fetch = vi.fn().mockResolvedValue({
        status: 429,
        headers: new Headers(),
        text: async () => JSON.stringify({ error: 'rate limited' }),
      });

      await expect(gemini.generateText(sampleRequest)).rejects.toThrow();
      expect(gemini.getHealth().isAvailable).toBe(false);

      // Now simulate a successful request
      globalThis.fetch = vi.fn().mockResolvedValue({
        status: 200,
        headers: new Headers(),
        text: async () =>
          JSON.stringify({
            candidates: [{ content: { parts: [{ text: 'Recovered!' }] } }],
          }),
      });

      const res = await gemini.generateText(sampleRequest);
      expect(res.text).toBe('Recovered!');
      expect(gemini.getHealth().isAvailable).toBe(true);
      expect(gemini.getHealth().cooldownUntil).toBeNull();
      expect(gemini.getHealth().lastSuccessAt).not.toBeNull();
    });

    it('does NOT pass provider-specific model override to fallback providers during failover', async () => {
      const registry = new AIProviderRegistry(mockConfig);
      const engine = new AIFailoverEngine(registry);

      let groqReceivedBody: any;
      globalThis.fetch = vi.fn().mockImplementation(async (url: string, opts: any) => {
        if (url.includes('generativelanguage.googleapis.com')) {
          // Gemini times out
          const err = new Error('Timeout');
          err.name = 'AbortError';
          throw err;
        }
        if (url.includes('api.groq.com')) {
          groqReceivedBody = JSON.parse(opts.body);
          return {
            status: 200,
            headers: new Headers(),
            text: async () => JSON.stringify({ choices: [{ message: { content: 'Groq reply' } }] }),
          };
        }
        throw new Error('Unexpected URL');
      });

      // Request specifies a Gemini-specific model override
      const customRequest: AITextRequest = {
        model: 'gemini-3.8-flash',
        messages: [{ role: 'user', content: 'Test' }],
      };

      const result = await engine.executeBackground(customRequest);
      expect(result.provider).toBe('groq');
      // Crucial: Groq must NOT have received 'gemini-3.8-flash'; it should use its own default 'llama-3.3-70b-versatile'
      expect(groqReceivedBody.model).toBe('llama-3.3-70b-versatile');
      expect(result.model).toBe('llama-3.3-70b-versatile');
    });
  });
});
